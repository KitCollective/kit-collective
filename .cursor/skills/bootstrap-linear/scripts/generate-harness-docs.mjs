#!/usr/bin/env node
/**
 * Generate AGENTS.md and the orchestration section of CONTEXT.md
 * from factory.config.json — same job Conductor’s FactoryHarnessContract does.
 *
 * Usage (from repo root):
 *   node scripts/generate-harness-docs.mjs
 *   node .cursor/skills/bootstrap-linear/scripts/generate-harness-docs.mjs
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_START = "<!-- factory:generated-start -->";
const GENERATED_END = "<!-- factory:generated-end -->";

function findRepoRoot(startDir) {
  let dir = startDir;
  for (let i = 0; i < 8; i += 1) {
    if (existsSync(join(dir, "factory.config.json"))) {
      return dir;
    }
    const parent = dirname(dir);
    if (parent === dir) {
      break;
    }
    dir = parent;
  }
  throw new Error("factory.config.json not found.");
}

const ROOT = findRepoRoot(dirname(fileURLToPath(import.meta.url)));
const config = JSON.parse(readFileSync(join(ROOT, "factory.config.json"), "utf8"));

const product = config.product?.name ?? "Product";
const teamKey = config.linear?.teamKey ?? "TEAM";
const teamName = config.linear?.teamName ?? "Engineering";
const approver = config.approver ?? "the approver";
const dispatch = config.dispatch?.state ?? "Backlog";
const integration = config.lanes?.integration ?? "development";
const staging = config.lanes?.staging ?? "staging";
const production = config.lanes?.production ?? "production";
const helpers = config.paths?.helpers ?? ".cursor/agents";
const specs = config.paths?.specs ?? ".scratch";
const signalCap = config.agent?.signalUpCapPerRun ?? 3;

function agentsMd() {
  return `<!-- Generated by scripts/generate-harness-docs.mjs from factory.config.json. Do not edit by hand. -->

# Agent instructions

Read \`factory.config.json\` then \`WORKFLOW.md\` before writing code or touching Linear.

## Which document wins

When two docs disagree, resolve in this order rather than following whichever you read first:

1. **\`CONTEXT.md\`** — the domain vocabulary. Highest authority on what a thing *is*.
2. **\`docs/design-system.md\`** — visual and interaction rules for in-scope surfaces (when the file exists). Agents flag gaps; they do not invent taste.
3. **\`docs/adr/\`** — accepted decisions, on why things are the way they are. An ADR marked superseded loses to the one that superseded it. Correct with a supersession note, never by rewriting.
4. **\`${specs}/<effort>/spec.md\`** — what one effort set out to build, frozen at write time. Specs go stale; treat them as intent, not as truth.
5. **The Linear issue** — tickets are subordinate to their spec.

**Code is evidence, not authority** — if the code contradicts \`CONTEXT.md\` or \`docs/design-system.md\`, one of them is a bug; say which rather than silently following the code.

If you find a genuine contradiction, surface it instead of picking a side quietly.

## Skill layers (do not mix)

| Path | What it is | Edit? |
| --- | --- | --- |
| \`factory.config.json\` | This product’s names, team key, lanes, labels. Copy from \`factory.config.example.json\` on a new repo. | Yes — per project. |
| \`.cursor/skills/\` | Working skills. Matt’s loop copied in, then this factory’s twist. YAML in \`agents/\`. | Yes — keep generic. |
| \`${helpers}/\` | Domain helpers spawned from \`/implement\` / \`/tdd\`. Product specialization. | Yes — per project. |

Factory slash commands are the **Cursor** skills.

## Agent skills

### Issue tracker

Work lives in Linear workspace **${product}**, team **${teamName}** (\`${teamKey}\`). See \`docs/agents/issue-tracker.md\`.

### Triage labels

Who-acts labels: \`needs-triage\`, \`needs-info\`, \`ready-for-agent\`, \`ready-for-human\`, \`wontfix\`, \`signal-up\`, \`proposal\`. See \`docs/agents/triage-labels.md\`. Dispatch = \`${dispatch}\` + \`ready-for-agent\` + unblocked.

### Signal-up

Out-of-scope bugs/debt: new Linear issue, \`${dispatch}\`, labels \`signal-up\` + \`needs-triage\` (never delegate, never \`ready-for-agent\`). Cap ${signalCap} per run. See \`docs/agents/signal-up.md\`.

### Qualified proposals

Out-of-scope features/optimisations: new Linear issue, \`${dispatch}\`, labels \`proposal\` + \`needs-triage\`. At most one per run. See \`docs/agents/qualified-proposals.md\`.

### Error ratcheting

Recurring mistakes become committed hooks or rules (tighten only; never loosen). See \`docs/agents/error-ratcheting.md\`.

### Write scope

Declare path globs on implementation issues (\`write-scope:\`) so parallel runs do not collide. See \`docs/agents/write-scope.md\`.

### Domain docs

Single-context layout: root \`CONTEXT.md\` + \`docs/adr/\`. See \`docs/agents/domain.md\`.

### Design system

Human \`/to-design\` writes \`docs/design-system.md\`. Implementing agents and the UI helper follow it and flag gaps instead of inventing taste. See \`.cursor/skills/to-design/SKILL.md\`.

### Codebase design

Deep-module vocabulary (module, interface, seam, adapter). \`/tdd\` and \`/to-spec\` consult it. Survey deepenings with \`/improve-codebase-architecture\`. See \`.cursor/skills/codebase-design/SKILL.md\`.

### Diagnosing bugs

Tight red-capable loop before a fix. Then \`/tdd\` at the seam, or \`/signal-up\` if out of scope. See \`.cursor/skills/diagnosing-bugs/SKILL.md\`.

### Wait what

Last message did not land. Re-pitch in \`CONTEXT.md\` language. See \`.cursor/skills/wait-what/SKILL.md\`.

### Skill router

Lost? \`/ask-me\` maps the situation to a factory skill. It hints; it does not fire another user-invoked skill. See \`.cursor/skills/ask-me/SKILL.md\`.

### Create a skill

New or edited factory skill under \`.cursor/skills/\`. Not a domain helper. See \`.cursor/skills/create-new-skill/SKILL.md\`.

### Vendor Expo skills

Official Expo/EAS skills live under \`.cursor/skills/expo/\` (not factory skills). \`/implement\` and the \`react-expo\` helper load \`expo-overview\` first, then the matching leaf. Checker \`/code-review\` Standards includes them when the diff touches \`apps/mobile\` or EAS. Product docs win on conflict. Do not recreate \`.agents/\`.

### Prototype, research, handoff, wizard

Throwaway design question: \`/prototype\`. Visual lock: \`/to-design\`. Cited primary sources: \`/research\`. Session must travel: \`/handoff\`. Human-only setup: \`/wizard\`.

### Planning stack

\`/grill-with-docs\` → \`/to-design\` (when UI needs shared rules) → \`/to-spec\` → \`/to-tickets\` → planner claims (\`${dispatch}\` + \`ready-for-agent\` + unblocked) → \`/implement\` (\`/tdd\`) → checker → ${approver} to Done → \`/land\` into \`${integration}\`. Milestone complete → staging. See \`docs/agents/planning-stack.md\`.

## How work enters the factory

1. \`/grill-with-docs\`
2. \`/to-design\` — HITL visual lock into \`docs/design-system.md\` when agents will implement UI
3. \`/to-spec\` — kickoff = Linear project + milestones; feature = document on an existing project
4. \`/to-tickets\` — vertical slices in \`${dispatch}\` with \`ready-for-agent\`
5. planner claims (unblocked) → implement → PR + Linear evidence → checker → \`Ready for merge\`
6. \`${approver}\` reads the GitHub PR, moves Linear to \`Done\`
7. \`/land\` into \`${integration}\`. A complete **milestone** then \`${staging}\` / \`${production}\` promotions

Product truth lives under \`${specs}\`. If a spec fights a stack lock, change the lock first.
`;
}

function orchestrationContext() {
  return `${GENERATED_START}
## Orchestration

Generated from \`factory.config.json\`. Do not put product nouns here.

**Control plane**:
Linear. Status + \`ready-for-agent\` + blockers decide what runs.
_Avoid_: GitHub Issues as source of truth, Linear Assignee → Agents → Cursor as dispatch

**Runtime**:
Cursor Automations + Cloud Agents reading this repo’s harness.
_Avoid_: Conductor board, local-only agents as the factory

**Kickoff**:
\`/to-spec\` for a new Linear project + milestones. No issues yet.
_Avoid_: creating tickets during spec

**Feature spec**:
\`/to-spec\` against an existing project.
_Avoid_: a second Linear project for the same effort

**Vertical slice**:
One issue that cuts schema → API → UI → tests and is demoable alone.
_Avoid_: horizontal tickets (schema-only, API-only)

**Dispatch**:
\`${dispatch}\` + label \`ready-for-agent\` + unblocked. Human remains assignee. Linear Agent stays empty (Cursor in that menu starts a Cloud Agent). Planner claim order = Linear priority (\`dispatch.priorityOrder\`).
_Avoid_: assigning Cursor as Agent or Assignee, treating priority as eligibility

**Workpad**:
The single workpad comment on an issue. \`### Review feedback\` is why a pass was sent back.
_Avoid_: a new comment thread per agent turn

**Signal-up**:
Out-of-scope bug or debt, filed as a new \`${dispatch}\` issue. Never coded in the current PR.
_Avoid_: expanding the PR, applying \`ready-for-agent\` to the finding

**Proposal**:
Out-of-scope feature or optimisation. Same ingress as signal-up, different label.
_Avoid_: mixing with \`signal-up\` on the same issue

**Land**:
Merge to \`${integration}\` after ${approver} moves the issue to Done.
_Avoid_: landing to ${staging} or ${production} from an issue run

**Promotion**:
A Linear **milestone** complete → \`${staging}\`; release helper → \`${production}\`. Separate from land. Not the whole project at once.
_Avoid_: deploy, release PR as a synonym for land, treating the Linear project as one staging dump

**Triage** *(Linear state)*:
Inbox for Sentry and other intake. Human accepts onto the board. Never auto-dispatch.
_Avoid_: the Triage *label group*, \`needs-triage\`

**Duplicate** *(Linear state)*:
This work already exists on another issue. No agent action.
_Avoid_: deleting the issue instead of marking duplicate

**Write scope**:
Path globs on an implementation issue the implementer may change.
_Avoid_: treating surface labels as write scope
${GENERATED_END}`;
}

function contextSkeleton() {
  return `# ${product}

Product domain vocabulary. Orchestration terms are generated. Expand language via \`/grill-with-docs\`.

${orchestrationContext()}

## Language

(Add product terms here. Matt format: **Term**: one or two sentences. _Avoid_: synonyms.)
`;
}

function upsertContext(existing) {
  const block = orchestrationContext();
  if (existing.includes(GENERATED_START) && existing.includes(GENERATED_END)) {
    return existing.replace(
      new RegExp(`${GENERATED_START}[\\s\\S]*?${GENERATED_END}`),
      block,
    );
  }
  const heading = existing.match(/^# .+$/m);
  if (heading) {
    const idx = existing.indexOf(heading[0]) + heading[0].length;
    return `${existing.slice(0, idx)}\n\n${block}\n${existing.slice(idx)}`;
  }
  return `${existing.trim()}\n\n${block}\n`;
}

const agentsPath = join(ROOT, "AGENTS.md");
writeFileSync(agentsPath, `${agentsMd().trim()}\n`);
console.log(`Wrote ${agentsPath}`);

const contextPath = join(ROOT, "CONTEXT.md");
if (!existsSync(contextPath)) {
  writeFileSync(contextPath, contextSkeleton());
  console.log(`Wrote ${contextPath} (skeleton)`);
} else {
  const next = upsertContext(readFileSync(contextPath, "utf8"));
  writeFileSync(contextPath, next.endsWith("\n") ? next : `${next}\n`);
  console.log(`Updated generated section in ${contextPath}`);
}
