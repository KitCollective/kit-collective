#!/usr/bin/env node
/**
 * Generate PI implement context and domain-helper wrappers from Desktop `.cursor` sources.
 *
 * Usage (repo root):
 *   node scripts/generate-pi-implement-context.mjs
 *   node scripts/generate-pi-implement-context.mjs --check
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  ALWAYS_RULES,
  ALWAYS_SKILLS,
  buildImplementAppendOverlay,
  GENERATED_CONTEXT_REL,
} from "../harness/implement-context.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const GENERATED_HEADER =
  "<!-- Generated by scripts/generate-pi-implement-context.mjs. Do not edit by hand. -->";

const IMPLEMENT_SKILL = ".cursor/skills/implement/SKILL.md";
const IMPLEMENT_EXCERPT_START = "## Unattended run";
const IMPLEMENT_EXCERPT_END = "## Domain helpers";

/** @type {Array<{ pi: string, cursor: string, inheritProjectContext?: boolean }>} */
export const PI_AGENT_MAP = [
  { pi: "nest", cursor: "backend-nest", inheritProjectContext: false },
  { pi: "expo", cursor: "react-expo", inheritProjectContext: false },
  { pi: "drizzle", cursor: "db-drizzle", inheritProjectContext: false },
  { pi: "ui-ux", cursor: "ui-ux", inheritProjectContext: false },
  { pi: "devops", cursor: "devops", inheritProjectContext: false },
];

/**
 * @param {string} rel
 * @returns {string}
 */
export function readRepoFile(rel) {
  return readFileSync(join(ROOT, rel), "utf8");
}

/**
 * @param {string} markdown
 * @returns {{ frontmatter: string, body: string }}
 */
export function splitFrontmatter(markdown) {
  if (!markdown.startsWith("---\n")) {
    return { frontmatter: "", body: markdown.trim() };
  }
  const end = markdown.indexOf("\n---\n", 4);
  if (end === -1) {
    return { frontmatter: "", body: markdown.trim() };
  }
  return {
    frontmatter: markdown.slice(4, end),
    body: markdown.slice(end + 5).trim(),
  };
}

/**
 * @param {string} frontmatter
 * @param {string} key
 * @returns {string | undefined}
 */
export function frontmatterValue(frontmatter, key) {
  const match = frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
  return match?.[1]?.trim();
}

/**
 * @param {string} skillMarkdown
 * @returns {string}
 */
export function extractImplementLoopExcerpt(skillMarkdown) {
  const start = skillMarkdown.indexOf(IMPLEMENT_EXCERPT_START);
  if (start === -1) {
    throw new Error(`${IMPLEMENT_SKILL}: missing ${IMPLEMENT_EXCERPT_START}`);
  }
  const end = skillMarkdown.indexOf(IMPLEMENT_EXCERPT_END, start);
  if (end === -1) {
    throw new Error(`${IMPLEMENT_SKILL}: missing ${IMPLEMENT_EXCERPT_END}`);
  }
  return skillMarkdown.slice(start, end).trim();
}

/**
 * @returns {string[]}
 */
export function missingImplementContextSources() {
  /** @type {string[]} */
  const missing = [];
  for (const rel of sourcePaths()) {
    if (!existsSync(join(ROOT, rel))) {
      missing.push(`missing source ${rel}`);
    }
  }
  return missing;
}

/**
 * @returns {string[]}
 */
export function sourcePaths() {
  const paths = [...ALWAYS_RULES, ...ALWAYS_SKILLS, IMPLEMENT_SKILL];
  for (const { cursor } of PI_AGENT_MAP) {
    paths.push(`.cursor/agents/${cursor}.md`);
  }
  return paths.sort();
}

/**
 * @param {string[]} paths
 * @returns {string}
 */
export function hashSources(paths) {
  const hash = createHash("sha256");
  for (const rel of paths) {
    hash.update(rel);
    hash.update("\0");
    hash.update(readRepoFile(rel));
    hash.update("\0");
  }
  return hash.digest("hex");
}

/**
 * @returns {string}
 */
export function buildImplementContextMarkdown() {
  const paths = sourcePaths();
  const digest = hashSources(paths);
  /** @type {string[]} */
  const parts = [
    GENERATED_HEADER,
    `<!-- sources-sha256: ${digest} -->`,
    "",
    "# PI implement context (always-on)",
    "",
    "Edit `.cursor/rules/*.mdc` and `.cursor/skills/*`; regenerate with `node scripts/generate-pi-implement-context.mjs`.",
    "",
    "# Factory rules",
    "",
  ];

  for (const ruleRel of ALWAYS_RULES) {
    parts.push(`## ${ruleRel}`, "", readRepoFile(ruleRel).trim(), "", "");
  }

  parts.push("# Factory skills", "");

  for (const skillRel of ALWAYS_SKILLS) {
    if (skillRel === IMPLEMENT_SKILL) {
      parts.push(
        `## ${skillRel} (loop excerpt)`,
        "",
        extractImplementLoopExcerpt(readRepoFile(skillRel)),
        "",
      );
      continue;
    }
    parts.push(`## ${skillRel}`, "", readRepoFile(skillRel).trim(), "", "");
  }

  parts.push("# PI worker overlays", "", buildImplementAppendOverlay().trim(), "");
  return `${parts.join("\n").trim()}\n`;
}

/**
 * @param {{ pi: string, cursor: string, inheritProjectContext?: boolean }} mapping
 * @returns {string}
 */
export function buildPiAgentMarkdown(mapping) {
  const cursorPath = `.cursor/agents/${mapping.cursor}.md`;
  const source = readRepoFile(cursorPath);
  const { frontmatter, body } = splitFrontmatter(source);
  const description =
    frontmatterValue(frontmatter, "description") ??
    `PI wrapper for ${cursorPath}. Regenerate; do not edit by hand.`;
  const inherit =
    mapping.inheritProjectContext === false ? "inheritProjectContext: false\n" : "";
  return `${GENERATED_HEADER}
---
name: ${mapping.pi}
description: ${description}
${inherit}---

${body}
`.trimEnd();
}

/**
 * @returns {Record<string, string>}
 */
export function buildPiAgentFiles() {
  /** @type {Record<string, string>} */
  const files = {};
  for (const mapping of PI_AGENT_MAP) {
    files[`.pi/agents/${mapping.pi}.md`] = `${buildPiAgentMarkdown(mapping)}\n`;
  }
  return files;
}

/**
 * @returns {{ implementContext: string, agents: Record<string, string> }}
 */
export function buildGeneratedOutputs() {
  return {
    implementContext: buildImplementContextMarkdown(),
    agents: buildPiAgentFiles(),
  };
}

/**
 * @param {{ write?: boolean }} [options]
 * @returns {{ changed: boolean, paths: string[] }}
 */
export function generatePiImplementContext(options = {}) {
  const write = options.write !== false;
  const { implementContext, agents } = buildGeneratedOutputs();
  const paths = [GENERATED_CONTEXT_REL, ...Object.keys(agents).sort()];
  /** @type {string[]} */
  const changedPaths = [];

  const contextPath = join(ROOT, GENERATED_CONTEXT_REL);
  mkdirSync(dirname(contextPath), { recursive: true });
  if (!existsSync(contextPath) || readFileSync(contextPath, "utf8") !== implementContext) {
    changedPaths.push(GENERATED_CONTEXT_REL);
    if (write) {
      writeFileSync(contextPath, implementContext);
    }
  }

  for (const [rel, content] of Object.entries(agents)) {
    const target = join(ROOT, rel);
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
      changedPaths.push(rel);
      if (write) {
        writeFileSync(target, content);
      }
    }
  }

  return { changed: changedPaths.length > 0, paths: changedPaths };
}

function isCli() {
  const entry = process.argv[1];
  if (!entry) {
    return false;
  }
  return resolve(entry) === fileURLToPath(import.meta.url);
}

if (isCli()) {
  const check = process.argv.includes("--check");
  const result = generatePiImplementContext({ write: !check });
  if (check) {
    if (result.changed) {
      console.error("generate-pi-implement-context: stale generated files:");
      for (const rel of result.paths) {
        console.error(`  - ${rel}`);
      }
      console.error("Run: node scripts/generate-pi-implement-context.mjs");
      process.exit(1);
    }
    console.log("generate-pi-implement-context: ok");
  } else {
    for (const rel of [GENERATED_CONTEXT_REL, ...Object.keys(buildPiAgentFiles()).sort()]) {
      console.log(`Wrote ${rel}`);
    }
  }
}
